// Its version must be the rustls-platform-verifier-android crate's, from Cargo.lock.
val rustlsVerifierVersion: String =
    rootProject.file("../../core/Cargo.lock").readLines().let { lines ->
        val at = lines.indexOfFirst { it.trim() == "name = \"rustls-platform-verifier-android\"" }
        require(at >= 0) { "rustls-platform-verifier-android not in core/Cargo.lock" }
        lines[at + 1].substringAfter('"').substringBefore('"')
    }

dependencies {
    implementation("org.rustls:rustls-platform-verifier:$rustlsVerifierVersion")
}
