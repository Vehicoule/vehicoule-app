#!/bin/sh
# Regenerates fixture.dart: the fake-catalog plugin (core/core/tests/guests) in a feed signed
# by a throwaway key, for bridge_test.dart (served by a local HttpServer, added by addFeed).
# The test runs on devices too, so the files travel as Dart constants.
set -eu
here=$(cd "$(dirname "$0")" && pwd)
core="$here/../../core"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

(cd "$core/core/tests/guests" && env -u CARGO_TARGET_DIR cargo build --release --target wasm32-wasip2 -q)
cp "$core/core/tests/guests/target/wasm32-wasip2/release/fake_catalog.wasm" "$tmp/fake.wasm"
printf '%s' '{"id":"fake","name":"Fake","version":"1.0.0","contract":"1.0","domains":["fake.test"]}' > "$tmp/fake.json"
sha() { shasum -a 256 "$1" | cut -d' ' -f1; }
cat > "$tmp/payload.json" <<EOF
{"name":"Test feed","sequence":1,"plugins":[{"id":"fake","version":"1.0.0","contract":"1.0",
"wasm_url":"fake.wasm","wasm_sha256":"$(sha "$tmp/fake.wasm")",
"manifest_url":"fake.json","manifest_sha256":"$(sha "$tmp/fake.json")"}]}
EOF
feed() { (cd "$core" && cargo run -q -p plugin-host --bin vehicoule-feed -- "$@"); }
key=$(feed keygen "$tmp/test.key" | sed -n 's/^public key: //p')
feed sign "$tmp/payload.json" "$tmp/test.key" > "$tmp/feed.json"

b64() { base64 < "$1" | tr -d '\n'; }
{
  echo '// Generated by make_fixture.sh: do not edit.'
  echo "const fixtureKey = '$key';"
  echo 'const fixtureFiles = <String, String>{'
  for f in feed.json fake.json fake.wasm; do echo "  '$f': '$(b64 "$tmp/$f")',"; done
  echo '};'
} > "$here/fixture.dart"
